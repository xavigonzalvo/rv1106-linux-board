#!/usr/bin/env python3
"""Layout phase L4: write design/pcb/routing-report.md from the measurements of check_routing.py / l4check.py
(design/pcb/l4/measured.json, design/pcb/check_routing.txt) and the router log (design/pcb/l4/routes.json).

    design/.venv/bin/python -I design/pcb/scripts/l4_report.py

Every number in the report is measured from the saved board by l4check.py (pcbnew geometry) or by KiCad DRC.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
PCB = os.path.normpath(os.path.join(HERE, ".."))


def main():
    m = json.load(open(os.path.join(PCB, "l4", "measured.json")))
    chk = open(os.path.join(PCB, "check_routing.txt"), encoding="utf-8").read().splitlines()
    routes = json.load(open(os.path.join(PCB, "l4", "routes.json")))
    head = chk[0]
    l4 = [ln for ln in chk[1:] if re.match(r"^\w+\s+L4-", ln)]
    drc = [ln for ln in chk[1:] if " drc " in ln[:16]]
    out = []
    w = out.append
    w("# Routing report - layout phase L4 (critical routing, gate TP-L4)")
    w("")
    w("Board `design/pcb/rv1106-reva.kicad_pcb`, rebuilt from the netlist by `design/pcb/scripts/rebuild_all.sh`. "
      "Every figure below is **measured from the saved board** by `scripts/l4check.py` (called by "
      "`scripts/check_routing.py`) or by KiCad 10 DRC (`kicad-cli pcb drc --severity-all`, zones refilled). "
      "Generated by `scripts/l4_report.py`; do not edit by hand.")
    w("")
    w("**Checker:** `%s`" % head)
    w("")
    other = [ln for ln in chk[1:] if ln.startswith("FAIL") and not re.match(r"^\w+\s+L4-", ln)]
    if other:
        w("FAIL lines outside the TP-L4 checks (the L5 watch list carried from L4 r1: header lanes that leave the SoC "
          "alone but not all together; not a TP-L4 item):")
        w("")
        for ln in other:
            w("- `%s`" % ln.strip()[:200])
        w("")
    l4f = [ln for ln in l4 if ln.startswith("FAIL")]
    w("TP-L4 check lines (L4-*): %d, of which FAIL: %d." % (len(l4), len(l4f)))
    w("")
    w("## DRC")
    w("")
    for ln in drc:
        w("- `%s`" % ln.strip())
    w("")
    w("## Ethernet (layout.md §4.2)")
    w("")
    w("| Pair | P (U9->link) | N | P_J (link->J3) | N_J | skew KiCad pair | skew U9->J3 | longest | vias P/N | "
      "coupled | uncoupled | gap on coupled runs |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for k, d in sorted(m.get("eth", {}).items()):
        w("| %s | %.2f | %.2f | %.2f | %.2f | %+.2f | %+.2f | %.2f | %d / %d | %.2f | %.2f | %.3f-%.3f |" % (
            k, d["P"], d["N"], d["P_J"], d["N_J"], d["skew_pair"], d["skew_total"], max(d["total_P"], d["total_N"]),
            d["vias_P"], d["vias_N"], d["coupled"], d["uncoupled"], d["gap_min"], d["gap_max"]))
    w("")
    w("TX-RX separation (tracks and vias outside the U9 fan): **%.3f mm** (>= 0.76). Nearest other-net track to an "
      "ETH line (outside the U9 courtyard): %s mm." % (m.get("eth_tx_rx_gap", 0), m.get("eth_other", ["?"])[0]))
    w("")
    w("## USB 2.0 (layout.md §4.6)")
    w("")
    w("P/N skew and lengths are measured **pad to pad** along the copper path (pad centre to pad centre, through the "
      "U2 / U1 flow-through pins and the J1 join; `scripts/pathlen.py`), once per USB-C plug orientation. Each line is "
      "sampled every 0.05 mm and classed: *coupled* (partner at the 0.255 / 0.152 mm pitch, 90 ohm), *0.42 mm* "
      "(lines > 0.45 mm apart widened to Z0 45 ohm, so the pair stays ~90 ohm differential; `tools/zsolve.py`), *hop* "
      "(within 1.5 mm of a via of the pair: the approved L4 hops, D-H5), *breakout* (within 1.5 mm of a pin of U9 / U11 / "
      "U2 / U1 / J1 / J4) and *uncontrolled* (anything else; FAIL above 1.0 mm per line).")
    w("")
    w("| Path | P line | N line | P / N length | skew | vias P / N | P: coupled / 0.42 mm / hop / breakout / "
      "uncontrolled | N: same |")
    w("|---|---|---|---|---|---|---|---|")
    for d in m.get("usb_paths", []):
        cp, cn = d["class_P"], d["class_N"]
        w("| %s | %s | %s | %.2f / %.2f | %+.2f | %d / %d | %.2f / %.2f / %.2f / %.2f / %.2f | "
          "%.2f / %.2f / %.2f / %.2f / %.2f |" % (
              d["path"], d["P"], d["N"], d["len_P"], d["len_N"], d["skew"], d["vias_P"], d["vias_N"],
              cp["coupled"], cp["wide"], cp["hop"], cp["breakout"], cp["other"],
              cn["coupled"], cn["wide"], cn["hop"], cn["breakout"], cn["other"]))
    w("")
    st = m.get("usbc_stubs", {})
    w("USB-C J1 join stubs (branch to the unused pin of the plug side, pad centre): %s." % ", ".join(
        "%s %s mm" % kv for kv in sorted(st.items())))
    w("")
    w("USB lines closer than 0.76 mm to other-net tracks / pads / vias (GND excluded; outside the breakout courtyards "
      "and the U9 ring-1 band): %s." % (", ".join("%s - %s %.3f mm" % (x[1], x[2], x[0]) for x in
                                                  m.get("usb_clearance", [])) or "none"))
    w("")
    w("**KiCad DRC and the USB pair rules:** KiCad pairs nets only by a `+`/`-` or `P`/`N` suffix, so it does not treat "
      "USB_DP/USB_DM, USBA_DP/DM, USBC_DP/DM (nor the ETH `_J` link nets) as differential pairs: the DRU skew, "
      "diff_pair_gap and diff_pair_uncoupled constraints of the USB class never run (probe by the L4 r1 verifier, "
      "D-112 d). 'DRC 0 errors' therefore says nothing about USB skew, gap or coupling; the authority for those is "
      "`l4check.py` (this report). The USB 30 mil clearance rules (tracks, and since D-112 pads and vias) are net-class "
      "rules and do run in DRC.")
    w("")
    w("| Lines (net totals, all copper incl. the J1 join legs) | P | N | difference |")
    w("|---|---|---|---|")
    for k, d in sorted(m.get("usb", {}).items()):
        w("| %s / %s | %.2f | %.2f | %+.2f |" % (k, k.replace("DP", "DM"), d["P"], d["N"], d["skew"]))
    w("")
    w("## Pair clearance, bends, hops")
    w("")
    w("ETH lines closer than 0.76 mm to other-net tracks / pads / vias (outside the U9 courtyard and ring-1 band): %s."
      % (", ".join("%s - %s %.3f mm" % (x[1], x[2], x[0]) for x in m.get("eth_clearance", [])) or "none"))
    w("")
    w("Bends sharper than 135 deg on ETH/USB L4 copper: %s." % (m.get("sharp_bends") or "none"))
    w("")
    w("L3 plane under the L4 hop copper: %s." % ", ".join("%s %.2f mm" % kv for kv in
                                                         sorted(m.get("hop_reference", {}).items())))
    w("")
    w("## Crystals (layout.md §4.3)")
    w("")
    w("| Net | length (all tracks) | §4.3 budget |")
    w("|---|---|---|")
    lim = {"OSC_XIN": 5, "OSC_XOUT_X": 5, "OSC_XOUT": 8, "RTC_XIN": 6, "RTC_XOUT": 6}
    for k, v in sorted(m.get("xtal", {}).items()):
        w("| %s | %.2f mm | <= %d mm |" % (k, v, lim[k]))
    w("")
    w("TP6 stub (R50.1 -> TP6.1): %.2f mm (<= 3 mm)." % m.get("tp6_stub", 0))
    w("")
    w("Crystal guard on all copper (other nets' L1 tracks, vias and L1 pads within 1 mm of the Y1/Y2/C76-C79 pads): %s."
      % (m.get("xtal_guard_all") or "none"))
    w("")
    w("## microSD and SPI NAND (layout.md §4.4)")
    w("")
    w("| Net | length | vs clock |")
    w("|---|---|---|")
    for grp in ("sd", "fspi"):
        d = m.get(grp, {})
        w("| **%s clock** | %.2f mm | - |" % (grp.upper(), d.get("CLK", 0)))
        for k, v in sorted(d.items()):
            if k != "CLK":
                w("| %s | %.2f mm | %+.2f mm |" % (k, v[0], v[1]))
    w("")
    w("## Buck cells (layout.md §4.5)")
    w("")
    w("| Cell | SW copper between pads | SW width | FB net copper | FB track to SW node |")
    w("|---|---|---|---|---|")
    for k, d in sorted(m.get("buck", {}).items()):
        w("| %s | %.2f mm | %.2f mm | %.2f mm | %.2f mm |" % (k, d["sw_len"], d["sw_w"], d["fb_len"], d["fb_to_sw"]))
    w("")
    w("## Power paths (layout.md §3)")
    w("")
    w("| Net | class width | narrowest L4-phase track | L4-phase vias |")
    w("|---|---|---|---|")
    for k, d in sorted(m.get("power", {}).items()):
        w("| %s | %s | %s | %s |" % (k, d.get("class_w", ""), d.get("min_w_l4", ""), d.get("vias_l4", "")))
    w("")
    w("## Connectivity of the TP-L4 net set (KiCad unconnected items)")
    w("")
    w("TP-L4 net set (D-112 k): every net of the classes ETH_DIFF, USB_DIFF, XTAL, SDMMC, FSPI, SW_NODE, ETH_CT, the "
      "buck *_FB nets, SDMMC_DET and the power-path nets (VBUS_IN, VBUS_5V, the four buck outputs, VCC_DDR, VCC_1V8, "
      "VCC3V3_SD and the plane nets). Nets that only share a name prefix (ETH_AVDD1V8, USB_SEL, USBA_VBUS_EN, "
      "SDMMC_PWREN: supply / control nets of class PWR_SUB / DEFAULT) are routed in L5 and listed in the check lines.")
    w("")
    bad = {k: v for k, v in m.get("connectivity", {}).items() if v}
    w("%d nets checked; open: %s" % (len(m.get("connectivity", {})), ", ".join(
        "%s (%d)" % kv for kv in sorted(bad.items())) or "none"))
    w("")
    w("## All L4 check lines")
    w("")
    w("```")
    for ln in l4:
        w(ln)
    w("```")
    w("")
    w("## Router log")
    w("")
    w("```")
    for ln in routes.get("log", []):
        if ln.startswith("  ") or ln.startswith("=="):
            w(ln)
    w("```")
    open(os.path.join(PCB, "routing-report.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote", os.path.join(PCB, "routing-report.md"))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Layout phase L5: append the L5 section to design/pcb/routing-report.md (after l4_report.py wrote the L4 part).

    design/.venv/bin/python -I design/pcb/scripts/l5_report.py

Everything comes from files the L5 scripts and the checker wrote from the saved board: check_routing.txt (L5-* lines
and the DRC lines), drc_routing.json, l5/lanes.json, l5/fr_routes.json, l5/script_routes.json, l5/stitch.json,
l5/silk.json, l5/cleanup.log. Do not edit the section by hand.
"""
import json
import os
import re
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
PCB = os.path.normpath(os.path.join(HERE, ".."))
L5 = os.path.join(PCB, "l5")
MARK = "<!-- L5-SECTION -->"


def load(name):
    p = os.path.join(L5, name)
    return json.load(open(p)) if os.path.exists(p) else {}


def main():
    rep = os.path.join(PCB, "routing-report.md")
    text = open(rep).read()
    if MARK in text:
        text = text[:text.index(MARK)]
    chk = open(os.path.join(PCB, "check_routing.txt")).read().splitlines()
    head = chk[0]
    l5lines = [ln for ln in chk if re.match(r"^\w+\s+L5-", ln)]
    drc = [ln for ln in chk if re.match(r"^\w+\s+drc ", ln)]
    fails = [ln for ln in chk if ln.startswith("FAIL")]
    lanes, fr, sc, st, silk = load("lanes.json"), load("fr_routes.json"), load("script_routes.json"), \
        load("stitch.json"), load("silk.json")
    pr, nd = load("priority.json"), load("north_d.json")
    src = {}
    for tag, d in (("lane router (l4lib, exact)", lanes), ("priority script (l4lib, exact, before Freerouting)", pr),
                   ("Freerouting 2.5.0", fr), ("script (l4lib, exact)", sc)):
        for n, r in d.get("routes", {}).items():
            if n == "GND":
                continue
            src.setdefault(n, []).append("%s: %d seg, %d via" % (tag, sum(len(t[1]) - 1 for t in r["tracks"]),
                                                                    len(r["vias"])))
    d = json.load(open(os.path.join(PCB, "drc_routing.json")))
    unc = Counter()
    for u in d["unconnected_items"]:
        m = re.search(r"\[([^\]]+)\]", u["items"][0]["description"])
        unc[m.group(1) if m else "?"] += 1
    out = [MARK, "", "# Layout phase L5 (remaining routing and finishing, gate TP-L5)", "",
           "Generated by `scripts/l5_report.py` from the saved board's checks; do not edit by hand.", "",
           "**Checker (final board):** `%s`" % head, "",
           "## KiCad DRC (zones filled, all severities, schematic parity off)", ""]
    out += ["- `%s`" % ln for ln in drc]
    out += ["", "## Open (unconnected) nets after L5", ""]
    if unc:
        out.append("| Net | unconnected items |")
        out.append("|---|---|")
        out += ["| %s | %d |" % kv for kv in sorted(unc.items())]
    else:
        out.append("none")
    out += ["", "## How each L5 net was routed", "", "| Net | routed by |", "|---|---|"]
    out += ["| %s | %s |" % (n, "; ".join(v)) for n, v in sorted(src.items())]
    out += ["", "Lane stubs (radial 0.10 mm neck-down exits through the ring-1 row): %d. Freerouting nets ripped by the "
            "exact check and re-routed by script: %s." % (len(lanes.get("stubs", {})),
                                                         ", ".join(fr.get("ripped", [])) or "none"), ""]
    if nd:
        pk = nd["pocket"]
        out += ["## Option D (north exit of U9): measured (scripts/l5_north_d.py)", "",
                "Pocket %s: %d via-site cells; at most %d lane vias mutually legal, %d in one row (y %.2f). TP31-TP6 "
                "gap at y 23.7: %.2f mm of lane centres (%d lanes). Lanes that can reach a pocket via site on L1 "
                "(each alone): %s." % (pk["area"], pk["via_site_cells"], pk["max_vias_mutually_legal"],
                                       pk["max_vias_one_row"], pk["best_row_y"] or 0,
                                       nd["tp_gap"]["free_centre_span_mm"], nd["tp_gap"]["lanes_0p10_at_0p25"],
                                       ", ".join("%s %d of %d" % (g, v["lanes_that_reach_a_pocket_via_site_alone"],
                                                                  len(v["lanes"])) for g, v in
                                                 sorted(nd["groups"].items()))), ""]
    if st:
        out += ["## GND stitching (scripts/l5_stitch.py)", "",
                "New GND vias: %d (%s). Places with no legal via site: %s." % (
                    len(st["routes"]["GND"]["vias"]), ", ".join("%s %d" % kv for kv in sorted(st["why"].items())),
                    ", ".join("%s %d" % (k, len(v)) for k, v in sorted(st["missing"].items()))), ""]
    if silk:
        nroom = [x for x in silk["labels"] if x[2] == "NO ROOM"]
        out += ["## Silkscreen (scripts/l5_silk.py)", "",
                "References placed: %d; hidden (no free spot, kept on F.Fab): %d (%s). Labels placed: %d; without room:"
                " %s." % (silk["refs_placed"], len(silk["refs_hidden"]), " ".join(silk["refs_hidden"]),
                          len(silk["labels"]) - len(nroom), ", ".join("%s (%s)" % (x[0], x[1]) for x in nroom) or
                          "none"), ""]
    out += ["## All L5 check lines", "", "```"] + l5lines + ["```", "", "## Every FAIL line of the final check", "",
                                                             "```"] + fails + ["```", ""]
    open(rep, "w").write(text.rstrip() + "\n\n" + "\n".join(out))
    print("routing-report.md: L5 section, %d L5 lines, %d FAIL lines" % (len(l5lines), len(fails)))


if __name__ == "__main__":
    main()

CREATED = {}   # functional name -> Part


def N(name):
    """Return the one global net with this name (creating it on first use)."""
    if name not in _NETS:
        n = Net(name)
        if name in POWER_NETS:
            n.drive = POWER       # rail nets are driven by a regulator/switch modelled with passive pins
        _NETS[name] = n
    return _NETS[name]


def part(func, kind, conns, place_near="", note=""):
    """Create the part named `func` (functional name in refmap.csv) of symbol `kind` and connect it.

    conns: {pin number or pin name: net name | None}; None = explicitly not connected (NC).
    Every symbol pin must appear in conns (no silent floating pins)."""
    assert func not in CREATED, f"{func} created twice"
    pre, pins, pinsrc = KIND[kind]
    if func in NOPART:
        k2, ref, fp, nnote = NOPART[func]
        assert k2 == kind
        fields = dict(LCSC="", MPN="", InBOM="no", exclude_from_bom="yes", Functional=func, Note=nnote)
        value = func
    elif func.startswith("TP_"):
        ref, fp, value = conns.pop("_ref"), TP_FOOTPRINT, func
        fields = dict(LCSC="", MPN="", InBOM="no", exclude_from_bom="yes", Functional=func,
                      Note="bare test pad (no BOM part); Phase 6 owns the TP list")
    else:
        rm = REFMAP[func]
        ref = rm["bom_ref"]
        row = BOM[ref]
        assert row["lcsc"] == rm["lcsc"], f"{func}: refmap LCSC {rm['lcsc']} != bom {row['lcsc']}"
        fp, value = row["footprint"], row["value"]
        # NB: no 'dnp'/'exclude_from_bom' field on fitted parts: SKiDL writes them as KiCad boolean properties
        # whose mere presence means TRUE (seen in board.net), so only copper-only parts carry exclude_from_bom.
        fields = dict(LCSC=row["lcsc"], MPN=row["mpn"], InBOM="yes", Functional=func,
                      LF_ref=rm["luckfox_ref"], Block=rm["block"])
    assert ref.startswith(pre) or (pre == "Q" and ref.startswith("Q")), f"{func}: ref {ref} vs symbol prefix {pre}"
    if place_near:
        fields["place_near"] = place_near
    if note:
        fields["Note"] = (fields.get("Note", "") + " " + note).strip()
    fields["pinout_source"] = pinsrc
    p = Part(tool=SKIDL, name=kind, ref_prefix=pre, footprint=fp, tag=func,
             pins=[Pin(num=n, name=nm, func=t) for n, nm, t in pins])
    p.ref = ref
    p.value = value
    for k, v in fields.items():
        p.fields[k] = v
    # resolve connections by pin number first, then by unique pin name
    done = set()
    for key, net in conns.items():
        nums = [n for n, nm, _ in pins if n == str(key)] or [n for n, nm, _ in pins if nm == str(key)]
        assert nums, f"{func}: no pin {key}"
        for num in nums:
            pin = _pin(p, num)
            if net is None:
                pin += NC
            else:
                n = N(net)
                n += pin
            done.add(num)
    missing = [n for n, _, _ in pins if n not in done]
    assert not missing, f"{func}: unconnected pins {missing} (use None for NC)"
    CREATED[func] = p
    return p


def _pin(p, num):
    for pin in p.pins:
        if str(pin.num) == str(num):
            return pin
    raise KeyError(num)


def two(func, kind, a, b, **kw):
    """2-terminal helper: pin 1 -> net a, pin 2 -> net b."""
    return part(func, kind, {"1": a, "2": b}, **kw)

"""Write a KiCad starter project for the H1 layout (design/kicad/rv1106-reva/).

Usage:  design/.venv/bin/python -I design/tools/make_kicad_project.py design

It writes:
  rv1106-reva.kicad_pro   net classes from layout/netclasses.csv, one exact-name pattern per net
  rv1106-reva.kicad_dru   copy of layout/board.kicad_dru (KiCad loads <project>.kicad_dru as Custom Rules)
  fp-lib-table            project library "board" -> ${KIPRJMOD}/board.pretty
  board.pretty/README.md  the custom footprints still to draw (layout.md §6.1, §6.4)
  place_parts.py          script for the PCB editor's scripting console: puts every footprint at its
                          fixed position or spreads it inside its zone (layout/placement.csv, zones.csv)

KiCad is not installed in the design environment, so the .kicad_pro keys and the pcbnew calls in
place_parts.py are UNVERIFIED (written for KiCad 8/9). kicad-guide.md gives the manual fallback for each.
Existing files are overwritten; nothing outside design/kicad/ is touched.
"""
import csv
import json
import shutil
import sys
from pathlib import Path

PROJECT = "rv1106-reva"

# Parts with a fixed position, from layout.md / decisions.md (board mm, y south). rot = KiCad orientation in degrees.
# Connectors come from zones.csv (origin_x, origin_y, rot_deg); these are the non-connector ones.
FIXED = {
    "U9": (34.5, 36.5, 90, "layout.md §5.2, D-84a: centre (34.5, 36.5), +90 deg, pin 1 SW"),
    "U8": (43.4, 62.6, 0, "D-91 (c): Z-USB south-east corner, rotation 0"),
    "JP1": (63.7, 35.0, 180, "D-91 (a): JP_MEAS_0V9 centre, rotation 180 (pad 2 west)"),
    "R30": (63.5, 16.5, None, "D-91 (a): R_MEAS_3V3 centre; rotation free"),
}

# Custom footprints the netlist names in the "board" library (layout.md §6.1, §6.4).
CUSTOM = [
    ("RV1106_QFN-128-1EP_12.3x12.3mm_P0.35mm", "U9", "layout.md §6.1 + §6.2 (pads, EP, thermal vias, paste windowpane); [DS] r1.8 Fig. 2-5 p.17"),
    ("TI_RSE0010A_UQFN-10_1.5x2mm_P0.5mm", "U11", "refs/ts3usb221a-datasheet, RSE0010A land pattern"),
    ("L_FHD4020S_4.0x4.0mm", "L1-L4", "refs/fhd4020s-datasheet (image-only drawing)"),
    ("SW_TS-1187A_5.1x5.1mm", "SW1-SW3", "refs/ts-1187a-datasheet p.1 'P.C.B LAYOUT'; pads 1=A 2=B 3=C 4=D"),
    ("microSD_TF-01A", "J2", "refs/tf-01a-datasheet p.1; pad 9 = card detect, SH = shell tabs"),
    ("USB_A_AF90_WJDG_RightAngle_THT", "J4", "refs/usb-a-af90-wjdg-datasheet p.1; pad 1 VBUS .. 4 GND, SH = shell"),
]

PLACE_SCRIPT = r'''# Run inside KiCad's PCB editor: Tools > Scripting Console, then
#   exec(open(r"<full path to this file>").read())
# Generated by design/tools/make_kicad_project.py. UNVERIFIED pcbnew calls (KiCad 8/9).
# Moves every footprint to its fixed position (connectors, U9, U8, JP1, R30) or spreads it inside its
# placement zone as a starting point. It does not route or rotate small parts. Undo with Ctrl+Z if needed.
import pcbnew

ORIGIN = (50.0, 50.0)   # board corner (0, 0) of layout.md lands here on the KiCad page, in mm
FIXED = %(fixed)s
ZONES = %(zones)s
PART_ZONE = %(part_zone)s
U9_KEEP = (26.0, 28.0, 43.0, 45.0)   # leave the SoC footprint area free when spreading Z-SOC parts

mm = pcbnew.FromMM
board = pcbnew.GetBoard()

def put(fp, x, y, rot=None):
    fp.SetPosition(pcbnew.VECTOR2I(mm(ORIGIN[0] + x), mm(ORIGIN[1] + y)))
    if rot is not None:
        fp.SetOrientationDegrees(rot)

missing, placed = [], 0
for ref, (x, y, rot) in FIXED.items():
    fp = board.FindFootprintByReference(ref)
    if fp is None:
        missing.append(ref)
        continue
    put(fp, x, y, rot)
    placed += 1

cursor = {}
for ref, zone in sorted(PART_ZONE.items(), key=lambda kv: (kv[1], kv[0])):
    if ref in FIXED:
        continue
    fp = board.FindFootprintByReference(ref)
    if fp is None:
        missing.append(ref)
        continue
    x0, y0, x1, y1 = ZONES[zone]
    bb = fp.GetBoundingBox()
    w, h = pcbnew.ToMM(bb.GetWidth()) + 0.6, pcbnew.ToMM(bb.GetHeight()) + 0.6
    cx, cy, row_h = cursor.get(zone, (x0 + 0.5, y0 + 0.5, 0.0))
    while True:
        if cx + w > x1:
            cx, cy, row_h = x0 + 0.5, cy + row_h, 0.0
        k = U9_KEEP
        if zone == "Z-SOC" and cx < k[2] and cx + w > k[0] and cy < k[3] and cy + h > k[1]:
            cx = k[2]
            continue
        break
    put(fp, cx + w / 2, cy + h / 2)
    cursor[zone] = (cx + w, cy, max(row_h, h))
    placed += 1

pcbnew.Refresh()
print("placed %%d footprints; missing from the board: %%s" %% (placed, missing or "none"))
print("Parts past a zone's south edge mean the zone is crowded: arrange them by hand (layout.md §5).")
'''


def main(design):
    design = Path(design)
    out = design / "kicad" / PROJECT
    (out / "board.pretty").mkdir(parents=True, exist_ok=True)

    rows = list(csv.DictReader(open(design / "layout" / "netclasses.csv")))
    classes, patterns = {}, []
    for r in rows:
        name = r["netclass"]
        classes.setdefault(name, r)
        if name != "DEFAULT":
            patterns.append({"netclass": name, "pattern": r["net"]})

    def nc(name, r):
        c = {
            "name": "Default" if name == "DEFAULT" else name,
            "clearance": float(r["clearance_mm"]),
            "track_width": float(r["width_mm"]),
            "via_diameter": 0.5,      # one via size everywhere: 0.3 / 0.5 mm (D-86)
            "via_drill": 0.3,
            "microvia_diameter": 0.3,
            "microvia_drill": 0.1,
            "wire_width": 6,
            "bus_width": 12,
            "line_style": 0,
            "pcb_color": "rgba(0, 0, 0, 0.000)",
            "schematic_color": "rgba(0, 0, 0, 0.000)",
        }
        if r["diff_gap_mm"]:
            c["diff_pair_width"] = float(r["width_mm"])
            c["diff_pair_gap"] = float(r["diff_gap_mm"])
            c["diff_pair_via_gap"] = float(r["diff_gap_mm"])
        else:
            c["diff_pair_width"] = 0.2
            c["diff_pair_gap"] = 0.25
            c["diff_pair_via_gap"] = 0.25
        return c

    ordered = ["DEFAULT"] + sorted(k for k in classes if k != "DEFAULT")
    pro = {
        "meta": {"filename": PROJECT + ".kicad_pro", "version": 1},
        "board": {"design_settings": {"rules": {
            "min_clearance": 0.1, "min_track_width": 0.1, "min_via_diameter": 0.5, "min_through_hole_diameter": 0.3,
            "min_hole_to_hole": 0.45, "min_copper_edge_clearance": 0.4}}},
        "net_settings": {
            "classes": [nc(k, classes[k]) for k in ordered],
            "meta": {"version": 3},
            "netclass_patterns": patterns,
        },
    }
    (out / (PROJECT + ".kicad_pro")).write_text(json.dumps(pro, indent=2) + "\n")
    shutil.copyfile(design / "layout" / "board.kicad_dru", out / (PROJECT + ".kicad_dru"))
    (out / "fp-lib-table").write_text(
        '(fp_lib_table\n  (version 7)\n'
        '  (lib (name "board")(type "KiCad")(uri "${KIPRJMOD}/board.pretty")(options "")'
        '(descr "Rev A custom footprints (layout.md §6)"))\n)\n')

    lines = ["# Custom footprints to draw (library `board`)", "",
             "Draw each in KiCad's Footprint Editor and save it here with exactly this name. Pad names must match",
             "decision D-74 (the netlist import reports a missing pad otherwise). Sources are under `design/refs/`.", "",
             "| Footprint name | Used by | Draw from |", "|---|---|---|"]
    lines += ["| `%s` | %s | %s |" % c for c in CUSTOM]
    lines += ["", "Fiducials: if `Fiducial:Fiducial_1mm_Mask2mm` is not in your KiCad libraries, draw one here as",
              "`Fiducial_1mm_Mask2mm` (1.0 mm round copper pad, 2.0 mm mask opening, no paste), layout.md §1."]
    (out / "board.pretty" / "README.md").write_text("\n".join(lines) + "\n")

    fixed = {ref: (x, y, rot) for ref, (x, y, rot, _src) in FIXED.items()}
    zones, part_zone = {}, {}
    for z in csv.DictReader(open(design / "layout" / "zones.csv")):
        if z["kind"] == "zone":
            zones[z["zone"]] = tuple(float(z[k]) for k in ("x0", "y0", "x1", "y1"))
        elif z["kind"] == "connector":
            ref = z["zone"].split("-")[0]
            fixed[ref] = (float(z["origin_x"]), float(z["origin_y"]), float(z["rot_deg"]))
    for p in csv.DictReader(open(design / "layout" / "placement.csv")):
        if p["zone"] in zones:
            part_zone[p["ref"]] = p["zone"]
        elif p["zone"] == "BOARD":
            continue            # D-117 j: parts moved by the routing phases into no zone (R62 / R63); see the target column
        elif p["ref"] not in fixed:
            sys.exit("placement.csv: %s has zone %s with no rectangle in zones.csv" % (p["ref"], p["zone"]))
    (out / "place_parts.py").write_text(PLACE_SCRIPT % {
        "fixed": json.dumps(fixed, indent=1).replace("null", "None"),
        "zones": json.dumps(zones, indent=1), "part_zone": json.dumps(part_zone, indent=1)})

    n_parts = len(set(part_zone) | set(fixed))
    print("wrote %s: %d net classes, %d net patterns, %d parts placed by script (%d fixed)"
          % (out, len(ordered), len(patterns), n_parts, len(fixed)))


if __name__ == "__main__":
    if len(sys.argv) != 2 or not Path(sys.argv[1], "layout").is_dir():
        sys.exit(__doc__)
    main(sys.argv[1])
